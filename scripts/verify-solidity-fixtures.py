#!/usr/bin/env python3
"""Verifies pinned local inputs without downloading or writing files."""
import hashlib
import json
import argparse
from pathlib import Path

repo = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--inputs-only', action='store_true', help='Verify sources before regenerating derived fixtures')
args = parser.parse_args()
fixture = repo / 'tests/fixtures/solidity'
count = 0
private_pins = {}
unavailable = set()
for manifest_name in ['PROTOCOL_INPUTS.json', 'SUPPLEMENTAL_INPUTS.json']:
    manifest = json.loads((fixture / manifest_name).read_text())
    for entry in manifest['files']:
        path = fixture / 'protocol-v5' / entry['path']
        relative = str(path.relative_to(repo))
        if entry['path'].startswith(('src/', 'test/')) or entry['path'] == 'foundry.toml':
            private_pins[relative] = entry['sha256']
            if not path.exists() and not args.inputs_only:
                unavailable.add(relative)
                continue
        if not path.is_file():
            raise SystemExit('Private integration sources required: use scripts/with-protocol-fixtures.py; missing ' + relative)
        if hashlib.sha256(path.read_bytes()).hexdigest() != entry['sha256']:
            raise SystemExit(f"Pinned input changed: {entry['path']}")
        count += 1
for package in json.loads((repo / 'tests/fixtures/uniswap-v3/MANIFEST.json').read_text()):
    for entry in package['artifacts']:
        path = repo / 'tests/fixtures/uniswap-v3' / entry['file']
        if hashlib.sha256(path.read_bytes()).hexdigest() != entry['sha256']:
            raise SystemExit(f"V3 artifact changed: {entry['file']}")
        count += 1
for name, expected in json.loads((repo / 'tests/fixtures/multicall3-PROVENANCE.json').read_text())['files'].items():
    if hashlib.sha256((repo / 'tests/fixtures' / name).read_bytes()).hexdigest() != expected:
        raise SystemExit(f'Multicall3 fixture changed: {name}')
    count += 1
if not args.inputs_only:
    generated = fixture / 'generated'
    manifest = json.loads((generated / 'SHA256.json').read_text())
    if not manifest.get('source_sha256'):
        raise SystemExit('Generated fixture source provenance missing; regenerate executor fixture')
    for relative, expected in manifest['source_sha256'].items():
        if relative in unavailable:
            if private_pins[relative] != expected:
                raise SystemExit(f'Generated fixture source changed: {relative}; regenerate executor fixture')
            continue
        if hashlib.sha256((repo / relative).read_bytes()).hexdigest() != expected:
            raise SystemExit(f'Generated fixture source changed: {relative}; regenerate executor fixture')
        count += 1
    for entry in manifest['files']:
        if hashlib.sha256((generated / entry['path']).read_bytes()).hexdigest() != entry['sha256']:
            raise SystemExit(f"Generated fixture changed: {entry['path']}")
        count += 1
print(f'Verified {count} pinned protocol/library/V3 input hashes')
if unavailable:
    print(f'{len(unavailable)} private source checks unavailable; pinned generated bytecode hashes verified')
